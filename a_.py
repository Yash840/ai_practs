import heapq

GOAL = (1, 2, 3,
        4, 5, 6,
        7, 8, 0)

def h(board):
    dist = 0

    for i, t in enumerate(board):
        cr, cc = divmod(i, 3)
        gr, gc = divmod(t - 1, 3)

        dist += abs(cr - gr) + abs(cc - gc)

    return dist

def neighbours(board):
    blank = board.index(0)
    r, c = divmod(blank, 3)

    for mv in (-3, 3, -1, 1):
        nxt = blank + mv

        if not 0 <= nxt < 9:
            continue

        if mv == -1 and c == 0:
            continue

        if mv == 1 and c == 2:
            continue

        new_board = list(board)

        new_board[blank], new_board[nxt] = new_board[nxt], new_board[blank]

        yield tuple(new_board)

def solve(start):
    q = [(h(start), 0, start)]

    best_g = {start: 0}
    parent = {start: None}

    while q:
        f, g, board = heapq.heappop(q)

        if board == GOAL:
            path = []

            while board is not None:
                path.append(board)
                board = parent[board]

            return path[::-1]

        for nxt in neighbours(board):
            new_g = g + 1
            new_f = new_g + h(nxt)

            if new_g != best_g.get(nxt, 999):
                continue

            best_g[nxt] = new_g
            parent[nxt] = board

            heapq.heappush(q, (new_f, new_g, nxt))

    return None

def print_board(board):
    for i in range(0, 9, 3):
        print(*[tile if tile else "_" for tile in board[i:i+3]])
    print()

start = (1, 2, 3,
         4, 0, 6,
         7, 5, 8)

path = solve(start)

if path is None:
    print("No solution found.")
else:
    print("Minimum moves:", len(path) - 1)

    for step, board in enumerate(path):
        print(f"Step {step}:")
        print_board(board)